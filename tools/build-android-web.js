'use strict';
// Packs the shared app for the Android WebView:
//   www/renderer/*      the same UI as the desktop app (+ mobile.css)
//   www/renderer/backend.js  main.js + core + preload.js bundled with phone shims
//   www/shared/*        brand + i18n
// Usage: node tools/build-android-web.js [outDir]   (default: android/app/src/main/assets/www)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.resolve(process.argv[2] || path.join(ROOT, 'android', 'app', 'src', 'main', 'assets', 'www'));
const VERSION = require('../package.json').version;

const ALIAS = {
  electron: 'src/mobile/shims/electron.js',
  fs: 'src/mobile/shims/fs.js',
  path: 'src/mobile/shims/path.js',
  os: 'src/mobile/shims/os.js',
  crypto: 'src/mobile/shims/crypto.js',
  url: 'src/mobile/shims/url.js',
};
const REDIRECT = {
  'src/main/platform.js': 'src/mobile/platform-android.js',
  'src/main/selftest.js': 'src/mobile/shims/selftest-stub.js',
};

function resolveReq(fromId, req) {
  if (ALIAS[req]) return ALIAS[req];
  if (!req.startsWith('.')) throw new Error(`Unknown module "${req}" required from ${fromId}`);
  const base = path.join(path.dirname(path.join(ROOT, fromId)), req);
  for (const cand of [base, `${base}.js`, `${base}.json`, path.join(base, 'index.js')]) {
    if (fs.existsSync(cand) && fs.statSync(cand).isFile()) {
      const id = path.relative(ROOT, cand).split(path.sep).join('/');
      return REDIRECT[id] || id;
    }
  }
  throw new Error(`Cannot resolve "${req}" from ${fromId}`);
}

function bundle(entry) {
  const mods = new Map();
  const queue = [entry];
  while (queue.length) {
    const id = queue.shift();
    if (mods.has(id)) continue;
    const src = fs.readFileSync(path.join(ROOT, id), 'utf8');
    const deps = {};
    if (!id.endsWith('.json')) {
      for (const m of src.matchAll(/require\((['"])([^'"]+)\1\)/g)) {
        const dep = resolveReq(id, m[2]);
        deps[m[2]] = dep;
        queue.push(dep);
      }
    }
    mods.set(id, { src, deps });
  }
  const parts = [];
  for (const [id, { src, deps }] of mods) {
    const body = id.endsWith('.json') ? `module.exports = ${src.trim()};` : src;
    parts.push(`${JSON.stringify(id)}: [function (module, exports, require, __dirname, __filename) {\n${body}\n}, ${JSON.stringify(deps)}]`);
  }
  return `/* Halyra Focus ${VERSION} — phone backend bundle (generated by tools/build-android-web.js) */
(function () {
  'use strict';
  var __APP_VERSION__ = ${JSON.stringify(VERSION)};
  window.__APP_VERSION__ = __APP_VERSION__;
  var defs = {
${parts.join(',\n')}
  };
  var cache = {};
  function load(id) {
    if (cache[id]) return cache[id].exports;
    var def = defs[id];
    if (!def) throw new Error('Module not bundled: ' + id);
    var module = { exports: {} };
    cache[id] = module;
    var dir = '/' + id.split('/').slice(0, -1).join('/');
    def[0].call(module.exports, module, module.exports, function (req) { return load(def[1][req]); }, dir, '/' + id);
    return module.exports;
  }
  load(${JSON.stringify(entry)});
})();
`;
}

function copyDir(src, dst, filter = () => true) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name);
    const d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d, filter);
    else if (filter(e.name)) fs.copyFileSync(s, d);
  }
}

function build() {
  fs.rmSync(OUT, { recursive: true, force: true });
  copyDir(path.join(ROOT, 'src', 'renderer'), path.join(OUT, 'renderer'), (n) => !/^overlay\./.test(n));
  copyDir(path.join(ROOT, 'src', 'shared'), path.join(OUT, 'shared'), (n) => n.endsWith('.js'));
  copyDir(path.join(ROOT, 'src', 'mobile', 'web'), path.join(OUT, 'renderer'));
  fs.writeFileSync(path.join(OUT, 'renderer', 'backend.js'), bundle('src/mobile/boot.js'));

  // Same page as the desktop app, plus: phone viewport, mobile styles, backend bundle,
  // and network access for account sync / the optional AI key.
  let html = fs.readFileSync(path.join(ROOT, 'src', 'renderer', 'index.html'), 'utf8');
  html = html
    .replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/, `<meta http-equiv="Content-Security-Policy" content="default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; script-src 'self'; font-src 'self'; connect-src 'self' https:; media-src 'self' blob: data:">\n  <meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, viewport-fit=cover">`)
    .replace('<link rel="stylesheet" href="styles.css">', '<link rel="stylesheet" href="styles.css">\n  <link rel="stylesheet" href="mobile.css">')
    .replace('<script src="app.js"></script>', '<script src="backend.js"></script>\n  <script src="app.js"></script>');
  if (!html.includes('backend.js') || !html.includes('mobile.css')) throw new Error('index.html changed shape; update build-android-web.js');
  fs.writeFileSync(path.join(OUT, 'renderer', 'index.html'), html);
  return OUT;
}

if (require.main === module) {
  const out = build();
  const size = fs.statSync(path.join(out, 'renderer', 'backend.js')).size;
  console.log(`Android web assets → ${out} (backend ${Math.round(size / 1024)} KB)`);
}
module.exports = { build, bundle };
